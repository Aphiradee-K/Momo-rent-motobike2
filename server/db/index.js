function dateStr(offsetDays = 0) {
  const d = new Date();
  d.setHours(12, 0, 0, 0);
  d.setDate(d.getDate() + offsetDays);
  return d.toISOString().slice(0, 10);
}

async function seedData() {
  const userCount = (await db.prepare("SELECT COUNT(*) AS n FROM users").get()).n;
  if (userCount === 0) {
    const insertUser = db.prepare(`
      INSERT INTO users (first_name, last_name, email, password_hash, role, address, phone)
      VALUES (?, ?, ?, ?, ?, ?, ?)
    `);
    await insertUser.run(
      "สมชาย", "ใจดี", "customer@test.com", bcrypt.hashSync("1234", 10), "customer",
      "123 ถ.สุขุมวิท แขวงคลองเตย เขตคลองเตย กรุงเทพฯ 10110", "081-234-5678"
    );
    await insertUser.run(
      "พนักงาน", "Momo", "staff@momo.com", bcrypt.hashSync("staff123", 10), "staff",
      "MOMO TRAVEL สำนักงานใหญ่ กรุงเทพฯ", "02-123-4567"
    );
    console.log("  ✔ seeded demo accounts");
  }

  const bikeCount = (await db.prepare("SELECT COUNT(*) AS n FROM bikes").get()).n;
  if (bikeCount === 0) {
    const insertBike = db.prepare(`
      INSERT INTO bikes (name, type, price, img, specs, cc, fuel, mpg, top_speed, seat, weight, starter, brake, color, features)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    `);
    for (const b of seedBikes) {
      const d = b.detail || {};
      await insertBike.run(
        b.name, b.type, b.price, b.img, JSON.stringify(b.specs || []),
        d.cc || "", d.fuel || "", d.mpg || "", d.topSpeed || "", d.seat || "",
        d.weight || "", d.starter || "", d.brake || "", d.color || "",
        JSON.stringify(d.feature || [])
      );
    }
    console.log(`  ✔ seeded ${seedBikes.length} motorcycles`);
  }

  const revenueCount = (await db.prepare("SELECT COUNT(*) AS n FROM demo_revenue").get()).n;
  if (revenueCount === 0) {
    const insertRevenue = db.prepare("INSERT INTO demo_revenue (year, month, amount) VALUES (?, ?, ?)");
    for (const [year, months] of Object.entries(demoRevenue)) {
      for (let i = 0; i < months.length; i++) {
        await insertRevenue.run(Number(year), i + 1, months[i]);
      }
    }
    console.log("  ✔ seeded historical revenue");
  }

  const bookingCount = (await db.prepare("SELECT COUNT(*) AS n FROM bookings").get()).n;
  if (bookingCount === 0) {
    const customer = await db.prepare("SELECT * FROM users WHERE email = ?").get("customer@test.com");
    const activeBike = await db.prepare("SELECT * FROM bikes WHERE name = ?").get("Honda Click 160");
    const doneBike = await db.prepare("SELECT * FROM bikes WHERE name = ?").get("Honda PCX 160");
    if (customer && activeBike && doneBike) {
      const insertBooking = db.prepare(`
        INSERT INTO bookings (user_id, bike_id, renter_name, phone, start_date, end_date, total, status, created_at)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
      `);
      const renter = `${customer.first_name} ${customer.last_name}`;
      await insertBooking.run(
        customer.id, activeBike.id, renter, customer.phone,
        dateStr(-2), dateStr(1), 3 * activeBike.price, "active",
        new Date(Date.now() - 2 * 86400000).toISOString()
      );
      await insertBooking.run(
        customer.id, doneBike.id, renter, customer.phone,
        dateStr(-40), dateStr(-37), 4 * doneBike.price, "done",
        new Date(Date.now() - 40 * 86400000).toISOString()
      );
      console.log("  ✔ seeded sample bookings");
    }
  }
}

const SEED_LOCK = 918273645;

let initPromise;
function init() {
  if (!initPromise) {
    initPromise = (async () => {
      if (usePostgres) {
        if (poolError) {
          throw new Error("DATABASE_URL (หรือ database) ไม่ถูกต้อง: " + poolError.message);
        }

        await pool.query(SCHEMA_POSTGRES);

        // Prevent multiple serverless instances from seeding at the same time.
        const client = await pool.connect();
        try {
          await client.query("SELECT pg_advisory_lock($1)", [SEED_LOCK]);
          await seedData();
        } finally {
          try { await client.query("SELECT pg_advisory_unlock($1)", [SEED_LOCK]); } catch {}
          client.release();
        }
      } else {
        // On Vercel, /tmp is ephemeral — fail with a clear message instead of
        // silently losing data (and instead of crashing at module load time).
        if (process.env.VERCEL) {
          throw new Error(
            "DATABASE_URL (หรือ database) is required on Vercel. ไปที่ Vercel > Settings > Environment Variables แล้วเพิ่ม DATABASE_URL จาก Neon (ใช้ตัวที่มี -pooler-)"
          );
        }

        if (!sqliteReady) {
          const { DatabaseSync } = require("node:sqlite");
          fs.mkdirSync(path.dirname(dbFile), { recursive: true });
          sqlite = new DatabaseSync(dbFile);
          sqlite.exec("PRAGMA journal_mode = WAL;");
          sqlite.exec("PRAGMA foreign_keys = ON;");
          sqliteReady = true;
        }

        sqlite.exec(SCHEMA_SQLITE);
        await seedData();
      }
    })().catch((err) => {
      initPromise = null;
      throw err;
    });
  }
  return initPromise;
}

