// ---------------------------------------------------------------------------
// Storage backend
//   - DATABASE_URL set  -> PostgreSQL (persistent, works on Vercel)
//   - not set           -> local SQLite file (handy for development)
// Both expose the same async `db.prepare(sql).get/all/run()` interface.
// ---------------------------------------------------------------------------
// Accept both the canonical name and the legacy short name used in this project's Vercel env.
const databaseUrl = process.env.DATABASE_URL || process.env.database;
const usePostgres = Boolean(databaseUrl);

let pool = null;
let poolError = null;
let sqlite = null;
let sqliteReady = false;
let dbFile;

if (usePostgres) {
  const connectionString = databaseUrl;
  try {
    const { Pool } = require("pg");

    let ssl;
    try {
      const url = new URL(connectionString);
      if (!["localhost", "127.0.0.1", "::1"].includes(url.hostname)) {
        ssl = { rejectUnauthorized: false };
      }
    } catch {
      ssl = { rejectUnauthorized: false };
    }

    pool = new Pool({
      connectionString,
      ssl,
      max: Number(process.env.PGPOOL_MAX) || 5,
      idleTimeoutMillis: 10000,
      connectionTimeoutMillis: 10000,
    });

    // Mask credentials for logs.
    dbFile = (() => {
      try {
        const u = new URL(connectionString);
        return `postgres://${u.hostname}${u.port ? ":" + u.port : ""}${u.pathname}`;
      } catch {
        return "PostgreSQL (DATABASE_URL)";
      }
    })();
  } catch (err) {
    poolError = err;
    dbFile = "PostgreSQL (DATABASE_URL)";
  }
} else {
  dbFile = path.resolve(
    process.cwd(),
    process.env.DB_FILE || (process.env.VERCEL ? "/tmp/momo.db" : "data/momo.db")
  );
}

