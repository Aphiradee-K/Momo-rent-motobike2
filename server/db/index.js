// ---------------------------------------------------------------------------
// Async SQLite-compatible adapter
// ---------------------------------------------------------------------------
const NUMERIC_ALIASES = new Set(["n", "amount", "count"]);

function normalizeRow(row) {
  if (!row) return row;
  const out = { ...row };
  for (const key of NUMERIC_ALIASES) {
    const value = out[key];
    if (typeof value === "string" && /^-?\d+$/.test(value)) out[key] = Number(value);
  }
  return out;
}

function toPostgres(sql, params) {
  let i = 0;
  return {
    text: sql.replace(/\?/g, () => `$${++i}`),
    values: params,
  };
}

const db = {
  prepare(sql) {
    return {
      async get(...params) {
        if (usePostgres) {
          const { text, values } = toPostgres(sql, params);
          const { rows } = await pool.query(text, values);
          return normalizeRow(rows[0] || null);
        }
        return normalizeRow(sqlite.prepare(sql).get(...params) || null);
      },

      async all(...params) {
        if (usePostgres) {
          const { text, values } = toPostgres(sql, params);
          const { rows } = await pool.query(text, values);
          return rows.map(normalizeRow);
        }
        return sqlite.prepare(sql).all(...params).map(normalizeRow);
      },

      async run(...params) {
        if (usePostgres) {
          let final = sql.trim().replace(/;+$/, "");
          if (/^INSERT\b/i.test(final) && !/\bRETURNING\b/i.test(final)) {
            // RETURNING * works for every table (demo_revenue has no `id` column).
            final += " RETURNING *";
          }
          const { text, values } = toPostgres(final, params);
          const res = await pool.query(text, values);
          const id = res.rows[0] && res.rows[0].id;
          return {
            lastInsertRowid: id === undefined ? undefined : Number(id),
            changes: res.rowCount,
          };
        }
        const res = sqlite.prepare(sql).run(...params);
        return {
          lastInsertRowid: Number(res.lastInsertRowid),
          changes: res.changes,
        };
      },
    };
  },

  async query(text, values = []) {
    if (usePostgres) return pool.query(text, values);
    throw new Error("db.query() is only available with PostgreSQL");
  },
};

